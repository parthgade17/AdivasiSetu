// Returns a localized string with fallback to Hindi (for related Indian languages) then English.
export function makeT(lang) {
  return (key, vars) => {
    let s = dict[lang]?.[key] ?? dict['hi']?.[key] ?? en[key] ?? key;
    if (vars && typeof s === 'string') {
      Object.entries(vars).forEach(([k, v]) => {
        s = s.replaceAll(`{${k}}`, v ?? '');
      });
    }
    return s;
  };
}
